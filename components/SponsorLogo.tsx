// Each viewBox is cropped to that mark's own ink, so none of them carry their
// file's padding into the layout.
//
// `optical` is the correction that makes a logo wall look right. Set every mark
// to the same measured height and a wide wordmark reads two or three times
// heavier than a compact round mark sitting next to it — same pixels, very
// different weight. These multipliers are tuned by eye against each other, and
// a new logo needs its own: start at 1 for a round or square mark, and around
// 0.65 for a full wordmark.
const LOGOS: Record<
  SponsorLogoKey,
  { viewBox: string; path: string; ratio: number; optical: number }
> = {
  tektite: {
    viewBox: '1.5 63.8 247 45.3',
    path: TEKTITE_PATH,
    ratio: 5.45,
    optical: 0.6,
  },
  github: { viewBox: '0 0 24 24', path: GITHUB_PATH, ratio: 1, optical: 1 },
  canva: { viewBox: '0 0 24 24', path: CANVA_PATH, ratio: 1, optical: 1 },
};

export function SponsorLogo({
  logo,
  name,
  /** Base height in px, before the per-logo optical correction. */
  height,
  className,
}: {
  logo: SponsorLogoKey;
  name: string;
  height: number;
  className?: string;
}) {
  const mark = LOGOS[logo];
  if (!mark) return null;

  const h = Math.round(height * mark.optical);

  return (
    <svg
      viewBox={mark.viewBox}
      role="img"
      aria-label={name}
      className={className}
      style={{ height: h, width: Math.round(h * mark.ratio) }}
    >
      <path d={mark.path} fill="currentColor" />
    </svg>
  );
}
